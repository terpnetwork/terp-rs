//! Rust crate generation from CosmWasm merged schemas.
//!
//! Each contract is a directory `api/rust/<contract>/` with `lib.rs` and `Cargo.toml`.

use crate::config::{contract_api_dir, GenerationContext};
use crate::resolver::SourceResolver;
use crate::{GenerationResult, Generator};
use std::collections::{HashMap, HashSet};

pub struct RustGenGenerator;

impl Generator for RustGenGenerator {
    fn name(&self) -> &'static str {
        "rust"
    }

    fn enabled_by_default(&self) -> bool {
        true
    }

    fn generate(&self, ctx: &GenerationContext) -> anyhow::Result<GenerationResult> {
        let rust_out = &ctx.rust_out;
        std::fs::create_dir_all(rust_out)?;

        let (_label, groups) = SourceResolver::resolve_grouped(ctx);
        if groups.is_empty() {
            log::warn!("[rust] No schema directories found");
            return Ok(GenerationResult {
                name: "rust",
                success: true,
                files_generated: 0,
                output_dir: Some(rust_out.to_string_lossy().to_string()),
                message: Some("No schema dirs found, skipping".into()),
            });
        }

        let mut total_files = 0;
        let mut contract_modules: Vec<String> = Vec::new();

        for (contract_name, schemas) in &groups {
            let safe_name = contract_name.replace('-', "_");
            let mut has_types = false;
            let mut struct_code = String::new();

            struct_code.push_str(&format!(
                "//! Generated CosmWasm types for `{contract_name}`.\n\
                 //! Code generated by gen-tools -- DO NOT EDIT.\n\n\
                 use cosmwasm_std::Binary;\n\
                 use schemars::JsonSchema;\n\
                 use serde::{{Deserialize, Serialize}};\n\n"
            ));

            let mut emitted: HashSet<String> = HashSet::new();

            for (_stem, merged) in schemas {
                // Extract message types (instantiate, execute, query, migrate, sudo)
                let msg_keys = ["instantiate", "execute", "query", "migrate", "sudo"];
                for key in &msg_keys {
                    if let Some(msg_val) = merged.get(*key) {
                        if msg_val.is_null() {
                            continue;
                        }
                        if let Some(title) = msg_val.get("title").and_then(|v| v.as_str()) {
                            let pascal = to_pascal_case(title);
                            if !pascal.is_empty() && emitted.insert(pascal.clone()) {
                                let s = schema_to_struct(&pascal, msg_val, "", &HashMap::new());
                                if !s.is_empty() {
                                    struct_code.push_str(&format!("// {key}\n{s}\n\n"));
                                    has_types = true;
                                }
                            }
                        }
                    }
                }

                // Response types (query responses)
                if let Some(responses) = merged.get("responses").and_then(|v| v.as_object()) {
                    for (qname, resp_schema) in responses {
                        let title = resp_schema
                            .get("title")
                            .and_then(|v| v.as_str())
                            .unwrap_or(qname);
                        let pascal = to_pascal_case(title);
                        if !pascal.is_empty() && emitted.insert(pascal.clone()) {
                            let s = schema_to_struct(&pascal, resp_schema, "", &HashMap::new());
                            if !s.is_empty() {
                                struct_code.push_str(&format!("// response {qname}\n{s}\n\n"));
                                has_types = true;
                            }
                        }
                    }
                }

                // Definitions — only emit if this schema has message types
                if has_types {
                    if let Some(defs) = merged.get("definitions").and_then(|v| v.as_object()) {
                        for (def_name, def_schema) in defs {
                            let pascal = to_pascal_case(def_name);
                            if emitted.insert(pascal.clone()) {
                                let s = schema_to_struct(&pascal, def_schema, "", &HashMap::new());
                                if !s.is_empty() {
                                    struct_code.push_str(&format!("{s}\n\n"));
                                }
                            }
                        }
                    }
                }
            }

            // Only write the contract file if it has actual types
            if has_types {
                let contract_dir = contract_api_dir(rust_out, contract_name);
                std::fs::create_dir_all(&contract_dir)?;
                let contract_file = contract_dir.join("lib.rs");
                std::fs::write(&contract_file, &struct_code)?;
                total_files += 1;
                let cargo_path = contract_dir.join("Cargo.toml");
                if !cargo_path.exists() {
                    std::fs::write(
                        &cargo_path,
                        format!(
                            "[package]\n\
                             name = \"{safe_name}\"\n\
                             version = \"0.1.0\"\n\
                             edition = \"2021\"\n\
                             publish = false\n\
                             description = \"Generated CosmWasm types for {contract_name}\"\n\
                             \n\
                             [dependencies]\n\
                             cosmwasm-std = \"1\"\n\
                             schemars = \"0.8\"\n\
                             serde = {{ version = \"1\", features = [\"derive\"] }}\n\
                             serde_json = \"1\"\n"
                        ),
                    )?;
                    total_files += 1;
                }
                contract_modules.push(safe_name);
            }
        }

        log::info!(
            "[rust] {} contract(s), {} file(s)",
            contract_modules.len(),
            total_files
        );

        Ok(GenerationResult {
            name: "rust",
            success: true,
            files_generated: total_files,
            output_dir: Some(rust_out.to_string_lossy().to_string()),
            message: Some(format!(
                "{} contract module(s), {} file(s)",
                contract_modules.len(),
                total_files
            )),
        })
    }
}

